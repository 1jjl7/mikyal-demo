"""
export_web.py - copies the engine's output files into the static web page.

Why: the page (web/) is static (GitHub Pages, opens from a QR code on any phone).
It can't run Python, so it reads what the engine already wrote. We put the CSVs
into one web/data.js file, so the page also opens straight from disk (file://)
on the demo laptop, with no server and no internet.

Run (after mikyal.py and backtest.py --tradeoff):
    python export_web.py
Out:
    ../web/data.js           - all outputs as JSON (what the page reads)
    ../web/data/*.csv        - the same CSVs, for download from the page
"""

import json
import re
import shutil
import time
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
OUT = HERE / "output"
WEB = HERE.parent / "web"
FILES = ["recommendations", "backtest_summary", "service_tradeoff", "backtest"]


def split_reason(reason):
    """'اطلب 3 كراتين. السبب: a + b + c. tip' -> head, [a, b, c], tip"""
    head, _, rest = str(reason).partition(". السبب: ")
    parts, _, tip = rest.partition(". ")
    parts = parts.rstrip(".")
    return head, [p.strip() for p in parts.split(" + ") if p.strip()], tip.strip()


def records(df):
    return json.loads(df.to_json(orient="records", force_ascii=False))


def main():
    data = {}
    for name in FILES:
        f = OUT / f"{name}.csv"
        if f.exists():
            data[name] = pd.read_csv(f, encoding="utf-8-sig")

    rec = data["recommendations"]
    split = rec["reason"].map(split_reason)
    rec["reason_head"] = split.str[0]
    rec["reason_parts"] = split.str[1]
    rec["reason_tip"] = split.str[2]

    # item settings the page shows next to each item (pack size, shelf life)
    folder = HERE / "data" / "SIMULATED"
    if (folder / "items.csv").exists():
        items = pd.read_csv(folder / "items.csv", encoding="utf-8-sig")
        data["items"] = items[["item", "category", "unit", "shelf_life_days", "pack_size"]]

    payload = {k: records(v) for k, v in data.items()}
    WEB.mkdir(exist_ok=True)
    (WEB / "data.js").write_text(
        "// generated by engine/export_web.py - do not edit by hand\n"
        f"window.MIKYAL_DATA = {json.dumps(payload, ensure_ascii=False)};\n",
        encoding="utf-8")

    (WEB / "data").mkdir(exist_ok=True)
    for name in FILES:
        f = OUT / f"{name}.csv"
        if f.exists():
            shutil.copy(f, WEB / "data" / f.name)
    # new version stamp, so phones don't keep yesterday's data.js / app.js in their cache
    index = WEB / "index.html"
    if index.exists():
        stamp = time.strftime("%Y%m%d%H%M%S")
        page = re.sub(r"\.(js|css)\?v=[0-9]+", rf".\1?v={stamp}", index.read_text(encoding="utf-8"))
        index.write_text(page, encoding="utf-8")
    print(f"saved {WEB / 'data.js'} ({', '.join(payload)})")


if __name__ == "__main__":
    main()
